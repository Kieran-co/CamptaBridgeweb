const { test } = require('node:test');
const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');
const { readFileSync } = require('node:fs');
const http = require('node:http');
const { chromium } = require('playwright');
test('aperçu vitrine : pages et démonstration navigables sans aucun service externe', async t => {
  execFileSync('python3', ['scripts/preview_vitrine.py']);
  const html = readFileSync('.build/apercu-refonte-site.html');
  const server = http.createServer((req, res) => { res.setHeader('Content-Type', 'text/html'); res.end(html); });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const origin = `http://127.0.0.1:${server.address().port}`;
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_EXECUTABLE_PATH ? { executablePath: process.env.CHROMIUM_EXECUTABLE_PATH } : {}) });
  t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1400, height: 1000 } });
  const outgoing = [], errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/*', route => {
    if (new URL(route.request().url()).origin === origin) return route.continue();
    outgoing.push(route.request().url()); return route.abort();
  });
  await page.goto(origin);
  const frame = page.frameLocator('iframe');
  await frame.getByRole('heading', { name: 'Votre facturation. L’esprit libre.', exact: true }).waitFor();
  await frame.locator('#site-navigation').getByRole('link', { name: 'Le logiciel', exact: true }).click();
  await frame.locator('[data-product-demo]').waitFor();
  await frame.getByRole('tab', { name: 'Suivre les règlements' }).click();
  assert.equal(await frame.locator('#demo-suivi').isVisible(), true);
  await page.locator('#preview-page').selectOption('telecharger.html');
  await frame.locator('[data-windows-download]').getByText(/nouvelle version Windows est en préparation/).waitFor();
  assert.equal(await frame.locator('[data-download-link]').isHidden(), true);
  await page.locator('#preview-page').selectOption('tarifs.html');
  await frame.getByRole('link', { name: 'Choisir le logiciel', exact: true }).click();
  await page.locator('#preview-notice').getByText(/désactivée dans cet aperçu/).waitFor();
  await page.locator('#preview-page').selectOption('legal/licence.html');
  await frame.getByRole('heading', { name: 'Conditions d’utilisation', exact: true }).waitFor();
  assert.deepEqual(outgoing, []); assert.deepEqual(errors, []);
});
